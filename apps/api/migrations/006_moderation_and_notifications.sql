CREATE TABLE notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(180) NOT NULL,
  body TEXT NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('announcement', 'review')),
  sender_uid BIGINT REFERENCES users(uid) ON DELETE SET NULL,
  post_id UUID REFERENCES posts(id) ON DELETE SET NULL,
  audience JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE notification_recipients (
  notification_id BIGINT NOT NULL REFERENCES notifications(id) ON DELETE CASCADE,
  user_uid BIGINT NOT NULL REFERENCES users(uid) ON DELETE CASCADE,
  read_at TIMESTAMPTZ,
  PRIMARY KEY (notification_id, user_uid)
);
CREATE INDEX notification_inbox ON notification_recipients(user_uid, notification_id DESC);
CREATE INDEX notification_unread ON notification_recipients(user_uid) WHERE read_at IS NULL;
