CREATE TABLE email_challenges (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  email TEXT NOT NULL,
  purpose TEXT NOT NULL CHECK (purpose IN ('registration', 'password_change', 'password_reset')),
  secret_hash TEXT NOT NULL,
  user_uid BIGINT REFERENCES users(uid) ON DELETE CASCADE,
  expires_at TIMESTAMPTZ NOT NULL,
  consumed_at TIMESTAMPTZ,
  attempts INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX email_challenge_lookup ON email_challenges(email, purpose, created_at DESC);
CREATE UNIQUE INDEX email_reset_secret ON email_challenges(secret_hash) WHERE purpose = 'password_reset';
CREATE TABLE email_deliveries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL,
  purpose TEXT NOT NULL,
  sent_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX email_delivery_rate ON email_deliveries(email, sent_at DESC);
