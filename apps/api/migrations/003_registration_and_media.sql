CREATE TABLE IF NOT EXISTS invitation_rules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  minimum_level INTEGER NOT NULL CHECK (minimum_level >= 1),
  quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 100),
  is_enabled BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS invitation_grants (
  user_uid BIGINT NOT NULL REFERENCES users(uid) ON DELETE CASCADE,
  rule_id BIGINT NOT NULL REFERENCES invitation_rules(id) ON DELETE CASCADE,
  PRIMARY KEY (user_uid, rule_id)
);
CREATE TABLE IF NOT EXISTS invitations (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  code TEXT NOT NULL UNIQUE,
  created_by BIGINT REFERENCES users(uid) ON DELETE SET NULL,
  rule_id BIGINT REFERENCES invitation_rules(id) ON DELETE SET NULL,
  max_uses INTEGER NOT NULL DEFAULT 1 CHECK (max_uses > 0),
  used_count INTEGER NOT NULL DEFAULT 0 CHECK (used_count >= 0 AND used_count <= max_uses),
  is_enabled BOOLEAN NOT NULL DEFAULT TRUE,
  expires_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS invitation_uses (
  invitation_id UUID NOT NULL REFERENCES invitations(id) ON DELETE CASCADE,
  user_uid BIGINT NOT NULL UNIQUE REFERENCES users(uid) ON DELETE CASCADE,
  used_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (invitation_id, user_uid)
);

