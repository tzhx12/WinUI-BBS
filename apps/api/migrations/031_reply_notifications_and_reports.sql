ALTER TABLE notifications DROP CONSTRAINT notifications_kind_check;
ALTER TABLE notifications ADD CONSTRAINT notifications_kind_check
  CHECK (kind IN ('announcement', 'review', 'moderation', 'storage', 'reply'));
ALTER TABLE notifications ADD COLUMN reply_id UUID REFERENCES replies(id) ON DELETE SET NULL;

CREATE TABLE notification_blocks (
  user_uid BIGINT NOT NULL REFERENCES users(uid) ON DELETE CASCADE,
  blocked_uid BIGINT NOT NULL REFERENCES users(uid) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (user_uid, blocked_uid),
  CHECK (user_uid <> blocked_uid)
);
CREATE INDEX notification_blocks_blocked ON notification_blocks(blocked_uid, user_uid);

CREATE TABLE content_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reporter_uid BIGINT REFERENCES users(uid) ON DELETE SET NULL,
  target_type TEXT NOT NULL CHECK (target_type IN ('post', 'reply', 'user')),
  target_post_id UUID,
  target_reply_id UUID,
  target_user_uid BIGINT,
  reason TEXT NOT NULL CHECK (char_length(reason) BETWEEN 1 AND 2000),
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'resolved')),
  resolution TEXT CHECK (resolution IN ('hide', 'delete', 'delete_ban', 'ban', 'delete_reply', 'dismiss')),
  resolved_by BIGINT REFERENCES users(uid) ON DELETE SET NULL,
  resolved_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (
    (target_type = 'post' AND target_post_id IS NOT NULL AND target_reply_id IS NULL AND target_user_uid IS NULL) OR
    (target_type = 'reply' AND target_post_id IS NOT NULL AND target_reply_id IS NOT NULL AND target_user_uid IS NULL) OR
    (target_type = 'user' AND target_post_id IS NULL AND target_reply_id IS NULL AND target_user_uid IS NOT NULL)
  )
);
CREATE INDEX content_reports_pending ON content_reports(created_at, id) WHERE status = 'pending';
CREATE INDEX content_reports_post ON content_reports(target_post_id) WHERE target_type = 'post';
CREATE INDEX content_reports_reply ON content_reports(target_reply_id) WHERE target_type = 'reply';
CREATE INDEX content_reports_user ON content_reports(target_user_uid) WHERE target_type = 'user';
CREATE UNIQUE INDEX content_reports_one_pending
  ON content_reports(reporter_uid, target_type, COALESCE(target_post_id::text, ''),
    COALESCE(target_reply_id::text, ''), COALESCE(target_user_uid::text, ''))
  WHERE status = 'pending' AND reporter_uid IS NOT NULL;
