CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS users (
  uid BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1) PRIMARY KEY,
  uuid UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  username VARCHAR(32) NOT NULL UNIQUE,
  email VARCHAR(320) NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  display_name VARCHAR(48) NOT NULL,
  bio TEXT NOT NULL DEFAULT '',
  avatar_url TEXT,
  experience BIGINT NOT NULL DEFAULT 0 CHECK (experience >= 0),
  level_offset INTEGER NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'suspended')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS user_groups (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(48) NOT NULL UNIQUE,
  group_type TEXT NOT NULL CHECK (group_type IN ('management', 'public', 'normal', 'temporary', 'special')),
  description TEXT NOT NULL DEFAULT '',
  is_joinable BOOLEAN NOT NULL DEFAULT FALSE,
  is_default BOOLEAN NOT NULL DEFAULT FALSE,
  is_protected BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS group_permissions (
  group_id BIGINT NOT NULL REFERENCES user_groups(id) ON DELETE CASCADE,
  permission_key TEXT NOT NULL,
  PRIMARY KEY (group_id, permission_key)
);

CREATE TABLE IF NOT EXISTS group_memberships (
  user_uid BIGINT NOT NULL REFERENCES users(uid) ON DELETE CASCADE,
  group_id BIGINT NOT NULL REFERENCES user_groups(id) ON DELETE CASCADE,
  expires_at TIMESTAMPTZ,
  joined_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (user_uid, group_id)
);

CREATE TABLE IF NOT EXISTS categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id BIGINT REFERENCES categories(id) ON DELETE SET NULL,
  name VARCHAR(64) NOT NULL,
  slug VARCHAR(72) NOT NULL UNIQUE,
  description TEXT NOT NULL DEFAULT '',
  accent_color VARCHAR(16) NOT NULL DEFAULT '#d85b45',
  minimum_reader_level INTEGER NOT NULL DEFAULT 0 CHECK (minimum_reader_level >= 0),
  minimum_author_level INTEGER NOT NULL DEFAULT 1 CHECK (minimum_author_level >= 1),
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS posts (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  category_id BIGINT NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
  author_uid BIGINT NOT NULL REFERENCES users(uid) ON DELETE RESTRICT,
  title VARCHAR(180) NOT NULL,
  body JSONB NOT NULL,
  minimum_reader_level INTEGER NOT NULL DEFAULT 0 CHECK (minimum_reader_level >= 0),
  status TEXT NOT NULL DEFAULT 'published' CHECK (status IN ('published', 'pending', 'hidden')),
  is_pinned BOOLEAN NOT NULL DEFAULT FALSE,
  view_count INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS posts_feed_idx ON posts(status, is_pinned DESC, created_at DESC);
CREATE INDEX IF NOT EXISTS posts_category_idx ON posts(category_id, created_at DESC);

CREATE TABLE IF NOT EXISTS replies (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  post_id UUID NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
  author_uid BIGINT NOT NULL REFERENCES users(uid) ON DELETE RESTRICT,
  body JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS replies_post_idx ON replies(post_id, created_at);

CREATE TABLE IF NOT EXISTS post_likes (
  post_id UUID NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
  user_uid BIGINT NOT NULL REFERENCES users(uid) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (post_id, user_uid)
);

CREATE TABLE IF NOT EXISTS experience_rules (
  action_key TEXT PRIMARY KEY,
  points INTEGER NOT NULL CHECK (points >= 0),
  is_enabled BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS daily_checkins (
  user_uid BIGINT NOT NULL REFERENCES users(uid) ON DELETE CASCADE,
  checkin_date DATE NOT NULL DEFAULT CURRENT_DATE,
  points INTEGER NOT NULL CHECK (points >= 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (user_uid, checkin_date)
);

CREATE TABLE IF NOT EXISTS level_titles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  minimum_level INTEGER NOT NULL CHECK (minimum_level >= 1),
  maximum_level INTEGER NOT NULL CHECK (maximum_level >= minimum_level),
  title VARCHAR(48) NOT NULL,
  color VARCHAR(16) NOT NULL DEFAULT '#486a5d'
);

CREATE TABLE IF NOT EXISTS app_settings (
  setting_key TEXT PRIMARY KEY,
  setting_value JSONB NOT NULL
);

CREATE TABLE IF NOT EXISTS emoji_packs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(64) NOT NULL UNIQUE,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS media_assets (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  storage_key TEXT NOT NULL UNIQUE,
  original_name TEXT NOT NULL,
  mime_type TEXT NOT NULL,
  byte_size BIGINT NOT NULL CHECK (byte_size >= 0),
  alt_text TEXT NOT NULL DEFAULT '',
  collection TEXT NOT NULL DEFAULT 'library' CHECK (collection IN ('library', 'emoji', 'site_icon')),
  emoji_pack_id BIGINT REFERENCES emoji_packs(id) ON DELETE SET NULL,
  created_by BIGINT REFERENCES users(uid) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS audit_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_uid BIGINT REFERENCES users(uid) ON DELETE SET NULL,
  action_key TEXT NOT NULL,
  target_type TEXT NOT NULL,
  target_id TEXT,
  details JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

