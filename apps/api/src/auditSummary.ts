function scalar(value: unknown, key: string): string {
  if (key === 'objectAccessMode')
    return ({ proxy: '服务器转发', presigned: '预签名 URL 直连', public: '自定义域名公开访问' } as Record<string, string>)[String(value)] || String(value)
  if (key === 'height' && (value === 50 || value === 75)) return value === 50 ? '固定半屏渐变' : '固定 3/4 屏渐变'
  if (value === null) return key === 'banMinutes' ? '解除封禁' : key === 'expiresAt' ? '永久' : '无'
  if (value === '') return '已清空'
  if (typeof value === 'boolean') return value ? '是' : '否'
  if (
    typeof value === 'string' &&
    [
      'status',
      'groupType',
      'group_type',
      'from',
      'to',
      'registrationMode',
      'type',
      'actionKey',
      'preference',
      'backend',
      'kind',
      'scope',
      'channel',
      'permissions',
      'removed',
    ].includes(key)
  )
    return values[value] || fields[value] || value
  return String(value)
}
function describe(value: unknown, path = '', key = ''): string[] {
  if (Array.isArray(value)) {
    if (!value.length) return [`${path}：无`]
    if (value.every((item) => item === null || typeof item !== 'object'))
      return [`${path}：${value.map((item) => scalar(item, key)).join('、')}`]
    return value.flatMap((item, index) => describe(item, `${path} ${index + 1}`, key))
  }
  if (value && typeof value === 'object')
    return Object.entries(value).flatMap(([field, entry]) =>
      describe(entry, [path, fields[field] || field].filter(Boolean).join(' · '), field),
    )
  return [`${path}：${scalar(value, key)}`]
}
export function auditSummary(entry: {
  action_key: string
  target_type: string
  target_id: string | null
  details: unknown
}) {
  const action = actions[entry.action_key] || entry.action_key
  const target = `${targets[entry.target_type] || entry.target_type}${entry.target_id ? ` #${entry.target_id}` : ''}`
  const lines = describe(entry.details)
  return {
    action,
    target,
    lines: lines.length
      ? lines
      : [
          `已${action.startsWith('执行') ? action : `执行“${action}”`}，对象：${target}。历史记录未保存内容摘要。`,
        ],
  }
}
